package app.webmirror.android

import app.webmirror.android.encode.HevcUtil
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

class HevcUtilTest {

    private fun bytes(vararg v: Int) = ByteArray(v.size) { v[it].toByte() }

    private val sc = bytes(0, 0, 0, 1)

    /** VPS + SPS + PPS as a hardware encoder emits them: Main profile, level 3.1 (93), with emulation prevention bytes. */
    private val mainL93 = sc + bytes(0x40, 0x01, 0x0C, 0x01, 0xFF, 0xFF, 0x01, 0x60, 0x00, 0x00, 0x03, 0x00, 0xB0, 0x00, 0x00, 0x03, 0x00, 0x00, 0x03, 0x00, 0x5D, 0x95, 0x98, 0x09) +
        sc + bytes(0x42, 0x01, 0x01, 0x01, 0x60, 0x00, 0x00, 0x03, 0x00, 0xB0, 0x00, 0x00, 0x03, 0x00, 0x00, 0x03, 0x00, 0x5D, 0xA0, 0x02, 0x80, 0x80, 0x2D, 0x16, 0x59, 0x59, 0xA4, 0x93, 0x2B, 0xC0, 0x40, 0x40, 0x00, 0x00, 0xFA, 0x40, 0x00, 0x1D, 0x4C, 0x02) +
        sc + bytes(0x44, 0x01, 0xC1, 0x72, 0xB4, 0x62, 0x40)

    @Test
    fun codecStringOfAMainProfileLevel93Sps() {
        assertEquals("hev1.1.6.L93.B0", HevcUtil.codecString(mainL93))
        assertEquals("main", HevcUtil.profileName("hev1.1.6.L93.B0"))
    }

    @Test
    fun threeByteStartCodesWork() {
        val sps = bytes(0, 0, 1, 0x42, 0x01, 0x01, 0x01, 0x60, 0x00, 0x00, 0x03, 0x00, 0x90, 0x00, 0x00, 0x03, 0x00, 0x00, 0x03, 0x00, 0x78, 0xA0)
        assertEquals("hev1.1.6.L120.90", HevcUtil.codecString(sps)) // level 4.0 = 120, constraint byte 0x90
    }

    @Test
    fun main10HighTierAndProfileSpace() {
        // profile_idc 2, compat flag 2 (-> 0x20000000, reversed 4), high tier, level 150 (5.0), constraint 0xB0
        val sps = sc + bytes(0x42, 0x01, 0x01, 0x22, 0x20, 0x00, 0x00, 0x03, 0x00, 0xB0, 0x00, 0x00, 0x03, 0x00, 0x00, 0x03, 0x00, 0x96)
        assertEquals("hev1.2.4.H150.B0", HevcUtil.codecString(sps))
        // profile_space 1 -> letter A
        val sps2 = sc + bytes(0x42, 0x01, 0x01, 0x41, 0x60, 0x00, 0x00, 0x03, 0x00, 0xB0, 0x00, 0x00, 0x03, 0x00, 0x00, 0x03, 0x00, 0x5D)
        assertEquals("hev1.A1.6.L93.B0", HevcUtil.codecString(sps2))
    }

    @Test
    fun nonZeroTrailingConstraintBytesAreKept() {
        val sps = sc + bytes(0x42, 0x01, 0x01, 0x01, 0x60, 0x00, 0x00, 0x03, 0x00, 0xB0, 0x00, 0x00, 0x03, 0x00, 0x00, 0x03, 0x00, 0x5D)
        assertEquals("hev1.1.6.L93.B0", HevcUtil.codecString(sps))
        val raw = sc + bytes(0x42, 0x01, 0x01, 0x01, 0x60, 0x00, 0x00, 0x03, 0x00, 0xB0, 0x00, 0x00, 0x03, 0x00, 0x00, 0x03, 0x05, 0x5D)
        assertEquals("hev1.1.6.L93.B0.0.0.0.0.5", HevcUtil.codecString(raw))
    }

    @Test
    fun noSpsMeansNull() {
        assertNull(HevcUtil.codecString(sc + bytes(0x40, 0x01, 0x0C, 0x01)))
        assertNull(HevcUtil.codecString(ByteArray(0)))
        assertNull(HevcUtil.codecString(sc + bytes(0x42, 0x01, 0x01))) // truncated SPS
    }

    @Test
    fun irapNalTypesAreKeyframes() {
        // IDR_W_RADL = 19 -> header byte 0x26; CRA = 21 -> 0x2A; TRAIL_R = 1 -> 0x02; AUD = 35 -> 0x46
        assertTrue(HevcUtil.isKeyframe(sc + bytes(0x26, 0x01, 0xAF, 0x08)))
        assertTrue(HevcUtil.isKeyframe(sc + bytes(0x2A, 0x01, 0xAF)))
        assertFalse(HevcUtil.isKeyframe(sc + bytes(0x02, 0x01, 0xD0, 0x10)))
        assertTrue(HevcUtil.isKeyframe(sc + bytes(0x46, 0x01, 0x50) + sc + bytes(0x26, 0x01, 0xAF)))
        assertFalse(HevcUtil.isKeyframe(ByteArray(0)))
    }
}
